<?php

/**
 * @file
 * Standalone form validation regression checks. Run with PHP CLI.
 */

require dirname(__DIR__) . '/ci_cantus_ids.module';

function t($message, $args = array()) {
  return strtr($message, $args);
}

function field_get_items($entity_type, $entity, $field_name) {
  return isset($entity->{$field_name}['und']) ? $entity->{$field_name}['und'] : FALSE;
}

function form_set_error($name, $message) {
  $GLOBALS['errors'][$name] = $message;
}

class CiSimilarGenreTestQuery {
  private $table;
  private $conditions = array();

  public function __construct($table) {
    $this->table = $table;
  }

  public function condition($name, $value, $operator = '=') {
    $this->conditions[$name] = $value;
    return $this;
  }

  public function fields($alias, $fields) { return $this; }
  public function range($start, $length) { return $this; }
  public function execute() { return $this; }

  public function fetchField() {
    foreach ($GLOBALS['parents'] as $nid => $parent) {
      if ($parent->title === $this->conditions['n.title'] &&
          $parent->type === $this->conditions['n.type']) {
        return $nid;
      }
    }
    return FALSE;
  }

  public function fetchObject() {
    if ($this->table !== 'aamerged') {
      throw new RuntimeException('Unexpected merged ID query.');
    }
    $GLOBALS['merged_checks']++;
    return FALSE;
  }
}

function db_select($table, $alias) {
  return new CiSimilarGenreTestQuery($table);
}

function node_load($nid) {
  return $GLOBALS['parents'][$nid];
}

function check($condition, $message) {
  if (!$condition) {
    throw new RuntimeException($message);
  }
}

$parents = array(1 => (object) array(
  'type' => 'master_chant',
  'title' => '005138',
  'field_genre' => array('und' => array(array('target_id' => 10))),
));
$merged_checks = 0;
$cases = 0;

// Preview uses the form-level validators in Backdrop core.
$form = array(
  '#validate' => array('node_form_validate'),
  'actions' => array('preview' => array('#submit' => array('node_form_preview'))),
);
$state = array();
ci_cantus_ids_form_alter($form, $state, 'master_chant_node_form');
check(in_array('ci_cantus_ids_master_chant_validate', $form['#validate']), 'Preview must inherit the custom validator.');
check(!isset($form['actions']['preview']['#validate']), 'Preview must not override the form validators.');

// Cover native taxonomy fields, entity references, and mixed configurations.
foreach (array('tid', 'target_id') as $parent_key) {
  foreach (array('tid', 'target_id') as $submitted_key) {
    $parents[1]->field_genre = array('und' => array(array($parent_key => 10)));
    // Both autogenerated and manually entered IDs must reject a different genre.
    foreach (array('', '005138.1') as $title) {
      foreach (array(10 => FALSE, 20 => TRUE) as $genre => $reject) {
        $errors = array();
        $state = array('values' => array(
          'title' => $title,
          'type' => 'master_chant',
          'field_similar_chant_id' => array('und' => array(array('value' => ' 005138 '))),
          'field_genre' => array('und' => array(array($submitted_key => (string) $genre))),
        ));
        ci_cantus_ids_master_chant_validate(array(), $state);
        check(isset($errors['field_similar_chant_id']) === $reject, 'Incorrect genre validation result.');
        if ($reject) {
          check(strpos($errors['field_similar_chant_id'], '005138') !== FALSE, 'Error must identify the Similar chant.');
        }
        $cases++;
      }
    }
  }
}
check($merged_checks === 8, 'Manual ID validation must still run only for nonempty titles.');

// Missing optional data must not cause warnings or reject unrelated references.
foreach (array(
  array(),
  array('field_similar_chant_id' => array('und' => array(array('value' => '   ')))),
  array('field_similar_chant_id' => array('und' => array(array('value' => 'unknown')))),
  array('field_related_chant_id' => array('und' => array(array('value' => '005138')))),
) as $fields) {
  $errors = array();
  $state = array('values' => $fields + array(
    'title' => '',
    'field_genre' => array('und' => array(array('target_id' => 20))),
  ));
  ci_cantus_ids_master_chant_validate(array(), $state);
  check(!$errors, 'Optional or unrelated references must not trigger a genre error.');
  $cases++;
}

echo "Passed $cases Similar chant genre validation checks.\n";
